import type { Readable } from 'node:stream';

/** A browser form POST target: send `fields` plus the file (as the last field, named "file") to `url`. */
export interface DirectUploadTarget {
  url: string;
  fields: Record<string, string>;
}

/**
 * Lets the browser upload straight to storage instead of through the API. Needed on hosts that cap
 * request bodies below the 5 MB slip limit (Vercel functions accept ~4.5 MB).
 */
export interface DirectUploads {
  /** A short-lived target that only accepts this key, this content type and at most `maxBytes`. */
  createTarget(key: string, options: { contentType: string; maxBytes: number }): Promise<DirectUploadTarget>;
  /** Size of a stored object, or null when it doesn't exist. */
  size(key: string): Promise<number | null>;
  /** The first `bytes` bytes of a stored object (for file-signature checks). */
  readStart(key: string, bytes: number): Promise<Buffer>;
  remove(key: string): Promise<void>;
}

/** Where uploaded salary slips live. Keys are generated by the server, never taken from the client. */
export interface StorageDriver {
  save(key: string, data: Buffer, contentType: string): Promise<void>;
  getStream(key: string): Promise<Readable>;
  /** Present only on drivers that support browser-to-storage uploads (S3). */
  direct?: DirectUploads;
}
